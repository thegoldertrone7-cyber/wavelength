#!/usr/bin/env node
'use strict';
/* Writes public/css/themes.css from public/js/themes.js.
   Run it after editing the theme list:  node scripts/gen-themes.js */
const fs = require('fs'), path = require('path');
const { all } = require('../public/js/themes.js');
const rgb = hex => { const h = hex.replace('#', ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)); };
const lin = c => { c /= 255; return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); };
const L = hex => { const [r, g, b] = rgb(hex); return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b); };
// whichever of black or white reads better on the accent
const onAccent = hex => (L(hex) + 0.05) / 0.05 > 1.05 / (L(hex) + 0.05) ? '#000' : '#fff';
let css = '/* Generated by scripts/gen-themes.js from public/js/themes.js. Do not edit by hand. */\n';
for (const t of all) {
  const [tr, tg, tb] = rgb(t.text), [ar, ag, ab] = rgb(t.accent), light = t.mode === 'light';
  css += `[data-theme=${t.id}]{--bg:${t.bg};--card:${t.card};--card2:${t.card2};--line:rgba(${tr},${tg},${tb},${light ? '.13' : '.09'});`
    + `--text:${t.text};--text2:${t.text2};--text3:${t.text3};--dot:rgba(${tr},${tg},${tb},${light ? '.22' : '.18'});`
    + `--invert:${t.text};--on-invert:${t.bg};--accent:${t.accent};--accent-rgb:${ar},${ag},${ab};--on-accent:${onAccent(t.accent)};color-scheme:${t.mode}}\n`;
}
fs.writeFileSync(path.join(__dirname, '..', 'public', 'css', 'themes.css'), css);
console.log(`wrote ${all.length} themes`);
